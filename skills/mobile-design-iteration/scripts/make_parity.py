#!/usr/bin/env python3
# WHAT: Generate parity.js from tokens.json: a self-contained use_figma script returning {ok:true} or a list of drifts between Figma variables/text styles and the Swift tokens.
# RUN: python3 make_parity.py [tokens.json] [parity.js], then paste parity.js as the code of one use_figma call in the app's design-system file
"""Generate parity.js — the drift check for the Figma design-system file.

The spec and the code must not disagree. A Figma file is a
fork by construction, so it needs something that fails loudly when it drifts. This
writes a self-contained script whose expected values come from tokens.json; run it in
the Figma file (the MCP's use_figma tool) and it returns a diff, or `{ok: true}`.

    python3 extract_tokens.py --repo <app repo>   # re-read the Swift
    python3 make_parity.py                        # regenerate the check
    # then run parity.js in the app's design-system Figma file

It reads variables and text styles only. Effect styles are skipped: Figma stores
shadow colours after its own rounding, so comparing them produces noise, not signal.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOKENS_PATH = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "tokens.json"
OUT_PATH = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "parity.js"
TOKENS = json.loads(TOKENS_PATH.read_text())


def rgb(hex_str: str) -> list:
    n = int(hex_str, 16)
    return [round(((n >> 16) & 255) / 255, 6), round(((n >> 8) & 255) / 255, 6), round((n & 255) / 255, 6)]


expected_palette = {name: rgb(hex_str) for name, hex_str in TOKENS["palette"].items()}

expected_roles = {}
for name, sides in TOKENS["roles"].items():
    out = {}
    for mode in ("light", "dark"):
        s = sides[mode]
        base = TOKENS["palette"][s["ref"]] if "ref" in s else s["hex"]
        out[mode] = rgb(base) + [s["alpha"]]
    expected_roles[name] = out

expected_text = {
    name: [v["size"], round(v["size"] * v["lineHeightMultiplier"], 1), v["weight"],
           round(v["trackingEm"] * 100, 4)]
    for name, v in TOKENS["text"].items()
}
expected_scale = {}
for group, key in (("Space", "space"), ("Radius", "radius"), ("Size", "size")):
    for name, value in TOKENS[key].items():
        expected_scale[f"{group}/{name}"] = value

JS = """// GENERATED by make_parity.py — do not edit by hand.
// Run in the app's design-system Figma file; returns {ok:true} or a list of drifts.
const PALETTE = %s;
const ROLES = %s;
const TEXT = %s;
const SCALE = %s;

const EPS = 0.002;
const near = (a, b) => Math.abs(a - b) <= EPS;
const drift = [];

const colorVars = await figma.variables.getLocalVariablesAsync("COLOR");
const floatVars = await figma.variables.getLocalVariablesAsync("FLOAT");
const cols = await figma.variables.getLocalVariableCollectionsAsync();
const theme = cols.find(c => c.name === "Theme");
const palCol = cols.find(c => c.name === "Palette");
const scaleCol = cols.find(c => c.name === "Scale");
if (!theme || !palCol || !scaleCol) return { ok: false, fatal: "a collection is missing" };

const modeOf = (col, name) => (col.modes.find(m => m.name === name) || {}).modeId;
const lightId = modeOf(theme, "Light"), darkId = modeOf(theme, "Dark");

const byShort = {};
for (const v of colorVars) byShort[`${v.variableCollectionId}|${v.name.split("/").pop()}`] = v;

// Resolve an alias down to a flat colour so a role is compared by what it renders.
function resolve(value, depth) {
  if (depth > 6) return null;
  if (value && value.type === "VARIABLE_ALIAS") {
    const t = colorVars.find(v => v.id === value.id);
    if (!t) return null;
    const firstMode = Object.keys(t.valuesByMode)[0];
    return resolve(t.valuesByMode[firstMode], depth + 1);
  }
  return value;
}

for (const [name, want] of Object.entries(PALETTE)) {
  const v = byShort[`${palCol.id}|${name}`];
  if (!v) { drift.push(`palette ${name}: missing in Figma`); continue; }
  const got = resolve(v.valuesByMode[palCol.modes[0].modeId], 0);
  if (!got || !near(got.r, want[0]) || !near(got.g, want[1]) || !near(got.b, want[2]))
    drift.push(`palette ${name}: Figma ${JSON.stringify(got)} vs Swift ${JSON.stringify(want)}`);
}

for (const [name, want] of Object.entries(ROLES)) {
  const v = byShort[`${theme.id}|${name}`];
  if (!v) { drift.push(`role ${name}: missing in Figma`); continue; }
  for (const [mode, modeId] of [["light", lightId], ["dark", darkId]]) {
    const got = resolve(v.valuesByMode[modeId], 0);
    const w = want[mode];
    if (!got) { drift.push(`role ${name}.${mode}: unresolved`); continue; }
    const a = got.a === undefined ? 1 : got.a;
    if (!near(got.r, w[0]) || !near(got.g, w[1]) || !near(got.b, w[2]) || !near(a, w[3]))
      drift.push(`role ${name}.${mode}: Figma ${[got.r, got.g, got.b, a].map(n => n.toFixed(3))} vs Swift ${w.map(n => Number(n).toFixed(3))}`);
  }
}

for (const [name, want] of Object.entries(SCALE)) {
  const v = floatVars.find(x => x.variableCollectionId === scaleCol.id && x.name === name);
  if (!v) { drift.push(`scale ${name}: missing in Figma`); continue; }
  const got = v.valuesByMode[scaleCol.modes[0].modeId];
  if (!near(got, want)) drift.push(`scale ${name}: Figma ${got} vs Swift ${want}`);
}

const styles = await figma.getLocalTextStylesAsync();
for (const [name, [size, line, weight, tracking]] of Object.entries(TEXT)) {
  const s = styles.find(x => x.name === `Text/${name}`);
  if (!s) { drift.push(`text ${name}: missing in Figma`); continue; }
  if (!near(s.fontSize, size)) drift.push(`text ${name}: size ${s.fontSize} vs ${size}`);
  if (s.fontName.style !== weight) drift.push(`text ${name}: weight ${s.fontName.style} vs ${weight}`);
  if (s.lineHeight.unit !== "PIXELS" || Math.abs(s.lineHeight.value - line) > 0.15)
    drift.push(`text ${name}: line ${JSON.stringify(s.lineHeight)} vs ${line}px`);
  if (s.letterSpacing.unit !== "PERCENT" || !near(s.letterSpacing.value, tracking))
    drift.push(`text ${name}: tracking ${JSON.stringify(s.letterSpacing)} vs ${tracking}%%`);
}

return drift.length ? { ok: false, drift } : {
  ok: true,
  checked: { palette: Object.keys(PALETTE).length, roles: Object.keys(ROLES).length,
             scale: Object.keys(SCALE).length, text: Object.keys(TEXT).length },
};
""" % (
    json.dumps(expected_palette, separators=(",", ":")),
    json.dumps(expected_roles, separators=(",", ":")),
    json.dumps(expected_text, separators=(",", ":")),
    json.dumps(expected_scale, separators=(",", ":")),
)

out = OUT_PATH
out.write_text(JS)
print(f"wrote {out} ({len(JS)} chars)")
print(f"  palette {len(expected_palette)}  roles {len(expected_roles)}  "
      f"scale {len(expected_scale)}  text {len(expected_text)}")
